def test_write_format(tmp_path):
    rows = [CplRow("C101", 25.9, -0.00004, TOP, 90.0), CplRow("U10", -14.17126, 3.0, BOTTOM, -55.0),
            CplRow("R1", 0.00006, -0.00006, TOP, 359.9996), CplRow("R2", 1, 2, TOP, 359.9994),
            CplRow("R3", 1, 2, BOTTOM, 112.5), CplRow("R4", -0.0, 0.0, TOP, -0.0)]
    p = tmp_path / "out.csv"
    write_cpl(p, rows)
    assert p.read_bytes() == (b"Designator,Mid X,Mid Y,Layer,Rotation\r\n"
                              b"C101,25.9000mm,0.0000mm,Top,90\r\n"
                              b"U10,-14.1713mm,3.0000mm,Bottom,305\r\n"
                              b"R1,0.0001mm,-0.0001mm,Top,0\r\n"
                              b"R2,1.0000mm,2.0000mm,Top,359.999\r\n"
                              b"R3,1.0000mm,2.0000mm,Bottom,112.5\r\n"
                              b"R4,0.0000mm,0.0000mm,Top,0\r\n")
    assert b"-0.0000" not in p.read_bytes()
    assert not [f for f in os.listdir(tmp_path) if f != "out.csv"]   # no temporary file left behind


@settings(max_examples=200, deadline=None)
@given(st.lists(st.tuples(st.floats(-500, 500), st.floats(-500, 500), st.sampled_from([TOP, BOTTOM]),
                          st.floats(-1000, 1000)), min_size=1, max_size=8))
def test_write_read_round_trip(tmp_path_factory, rows):
    p = tmp_path_factory.mktemp("rt") / "cpl.csv"
    src = [CplRow(f"U{i}", x, y, layer, a) for i, (x, y, layer, a) in enumerate(rows)]
    write_cpl(p, src)
    for a, b in zip(src, read_cpl(p)):
        assert abs(a.x - b.x) <= 5.1e-5 and abs(a.y - b.y) <= 5.1e-5 and a.layer == b.layer
        assert abs((a.rotation - b.rotation + 180) % 360 - 180) <= 5.1e-4
        assert 0 <= b.rotation < 360
        assert "-0.0000" not in format_row(b)[1:3]


