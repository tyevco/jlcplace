def _part(ref, layer=TOP, x=110.0, y=90.0, angle=0.0, lcsc="C1", **kw):
    return Part(ref, layer, x, y, angle, lcsc=lcsc, pads=[Pad("1", -0.5, 0, 0.5, 0.5), Pad("2", 0.5, 0, 0.5, 0.5)],
                **kw)


def test_rows_for_board_selection_order_and_keys():
    parts = [_part("R10", lcsc="C2"), _part("R2", layer=BOTTOM, angle=30, lcsc="C2"), _part("R1", lcsc=""),
             _part("R3", dnp=True), _part("R4", exclude_pos=True), _part("R5", board_only=True),
             _part("R6", exclude_bom=True), _part("U1", lcsc="C9"), _part("U2", lcsc="C8"), _part("U10", lcsc="C2")]
    board = Board("x", (100.0, 100.0), parts)
    corrs = {"C2": Correction(rot=90, dx=0.1, dy=0.0), "U10": Correction(rot=180), "C8": Correction(0, mirror=True)}
    rows, missing = rows_for_board(board, corrs)
    assert [r.ref for r in rows] == ["R2", "R10", "U10"]
    assert missing == ["U1", "U2"]                     # no correction; mirrored correction
    r2 = rows[0]
    assert (r2.layer, r2.rotation) == (BOTTOM, cv.jlc_angle(30, 90, BOTTOM))
    assert (r2.x, r2.y) == cv.cpl_row_for(parts[1], corrs["C2"], (100.0, 100.0))[:2]
    assert rows[2].rotation == 180.0                   # the reference key wins over the code
    alt, _ = rows_for_board(board, corrs, reading="ccw-from-top")
    assert alt[0].rotation == cv.jlc_angle(30, 90, BOTTOM, "ccw-from-top") != r2.rotation
    # JLC places what its BOM lists, whatever the board excludes it from (KiCad's attributes), never a DNP part
    listed, _ = rows_for_board(board, {"C1": Correction(0), **corrs}, bom_refs={"R3", "R4", "R5", "R6", "R10"})
    assert [r.ref for r in listed] == ["R2", "R4", "R6", "R10", "U10"]


def test_rows_for_board_places_ee_footprint_on_kicad_footprint():
    """The written rows, read back and placed as JLC does, put each EasyEDA point where the KiCad library puts it."""
    rnd = random.Random(5)
    parts, corrs = [], {}
    for i in range(60):
        p = _part(f"U{i}", layer=rnd.choice([TOP, BOTTOM]), x=rnd.uniform(60, 160), y=rnd.uniform(40, 140),
                  angle=rnd.choice([0, 90, 180, 270, rnd.uniform(0, 360)]), lcsc=f"C{i + 1}")
        parts.append(p)
        corrs[p.lcsc] = Correction(rot=rnd.choice([0, 90, 180, 270, rnd.uniform(0, 360)]), dx=rnd.uniform(-2, 2),
                                   dy=rnd.uniform(-2, 2))
    board = Board("x", (100.0, 100.0), parts)
    rows, missing = rows_for_board(board, corrs)
    assert not missing
    for r in rows:
        p = board.part(r.ref)
        c = corrs[p.lcsc]
        C = cv.cpl_to_board((r.x, r.y), board.origin)
        for _ in range(4):
            e = (rnd.uniform(-3, 3), rnd.uniform(-3, 3))
            want = cv.library_to_board(p, cv.ee_to_library(c, e))
            assert math.dist(cv.ee_to_board(e, C, r.rotation, r.layer), want) < 2e-4


