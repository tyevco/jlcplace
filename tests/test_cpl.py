    "Designator,Mid X,Mid Y,Layer,Rotation\r\nU1,10.5mm,-2.25mm,Top,90\r\nU2,1mm,2mm,Bottom,270\r\n",
    "designator,MID X,mid y,LAYER,rotation\nU1,10.5,-2.25,top,90\nU2,1,2,bottom,-90\n",
    "Ref,PosX,PosY,Side,Rot\nU1,10.5,-2.25,T,90.0\nU2,1.0,2.0,B,270.0\n",
    "Reference;Center-X(mm);Center-Y(mm);Layer;Angle\nU1;10,5;-2,25;TopLayer;90\nU2;1;2;BottomLayer;270\n",
    "Designator\tX\tY\tSide\tRotation\nU1\t10.5 mm\t-2.25 mm\tFront\t90°\nU2\t1\t2\tBack\t270 deg\n",
    "Designator,Center-X(mil),Center-Y(mil),Layer,Rotation\nU1,413.38582677,-88.58267717,F.Cu,90\n"
    "U2,39.37007874,78.74015748,B.Cu,270\n",
    "Designator,Mid X,Mid Y,Layer,Rotation\nU1,0.41338582677in,-88.58267717mil,F,90\nU2,1mm,2mm,b,630\n",
    "Generated by some tool\n\nDesignator,Mid X,Mid Y,Layer,Rotation\nU1,10.5mm,-2.25mm,Top,90\n"
