def test_units_argument_and_parsers():
    assert parse_length("500mil") == pytest.approx(12.7)
    assert parse_length("0.5 in") == pytest.approx(12.7)
    assert parse_length("12,7") == pytest.approx(12.7)
    assert parse_length("0.5", "in") == pytest.approx(12.7)
    assert parse_length("-0") == 0.0 and math.copysign(1, parse_length("-0")) == 1.0
    for s in ("Top", "T", "top", "F", "Front", "F.Cu", "TopLayer"):
        assert parse_layer(s) == TOP
    for s in ("Bottom", "B", "bottom", "Back", "B.Cu", "BottomLayer", "bot"):
        assert parse_layer(s) == BOTTOM


