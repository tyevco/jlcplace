def test_header_value_and_layer_variants(tmp_path, text):
    rows = by_ref(read_cpl(write(tmp_path, "cpl.csv", text)))
    assert set(rows) == {"U1", "U2"}
    u1, u2 = rows["U1"], rows["U2"]
    assert math.isclose(u1.x, 10.5, abs_tol=1e-6) and math.isclose(u1.y, -2.25, abs_tol=1e-6)
    assert (u1.layer, u1.rotation) == (TOP, 90.0)
    assert math.isclose(u2.x, 1.0, abs_tol=1e-6) and math.isclose(u2.y, 2.0, abs_tol=1e-6)
    assert (u2.layer, u2.rotation) == (BOTTOM, 270.0)


