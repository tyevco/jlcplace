@pytest.mark.pcbnew
def test_real_kicad_position_files_read_alike_and_match_the_board(kicad_pos):
    """kicad-cli's four text formats give the same rows, and they are the cpl frame: aux-origin relative, y up,
    KiCad's own angle, X not mirrored on the bottom."""
    pcbnew = pytest.importorskip("pcbnew")
    ref = by_ref(read_cpl(kicad_pos["csv", "mm"]))
    tol = {("csv", "mm"): 1e-6, ("ascii", "mm"): 1e-4, ("csv", "in"): 25.4e-6, ("ascii", "in"): 25.4e-4}
    for key, path in kicad_pos.items():
        rows = by_ref(read_cpl(path, units=key[1] if key[0] == "csv" else "mm"))
        assert set(rows) == set(ref), key
        for r in rows.values():
            q = ref[r.ref]
            assert abs(r.x - q.x) <= tol[key] and abs(r.y - q.y) <= tol[key], (key, r, q)
            assert r.layer == q.layer and abs((r.rotation - q.rotation + 180) % 360 - 180) <= 1e-3
    kb = pcbnew.LoadBoard(MAIN_PCB)
    org = kb.GetDesignSettings().GetAuxOrigin()
    origin = (pcbnew.ToMM(org.x), pcbnew.ToMM(org.y))
    seen = set()
    for fp in kb.GetFootprints():
        if fp.GetAttributes() & pcbnew.FP_EXCLUDE_FROM_POS_FILES:
            assert fp.GetReference() not in ref
            continue
        r = ref[fp.GetReference()]
        x, y = cv.board_to_cpl((pcbnew.ToMM(fp.GetPosition().x), pcbnew.ToMM(fp.GetPosition().y)), origin)
        assert (r.x, r.y) == (pytest.approx(x, abs=1e-6), pytest.approx(y, abs=1e-6))
        assert r.layer == (BOTTOM if fp.IsFlipped() else TOP)
        assert r.rotation == cv.norm_angle(round(fp.GetOrientationDegrees(), 6))
        seen.add(r.ref)
    assert seen == set(ref) and any(r.layer == BOTTOM for r in ref.values())


