#!/usr/bin/env python3
"""Write docs/reference/cli.md from jlcplace's own argument parser, so the reference cannot drift from the CLI.

    python docs/gen_cli.py            # rewrite docs/reference/cli.md
    python docs/gen_cli.py --check    # exit 1 if the committed page is out of date (tests/test_docs.py does this)

The default cache directory depends on the machine, so the page shows the documented default instead.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "reference" / "cli.md"
CACHE_DEFAULT = "~/.cache/jlcplace"

HEADER = """\
# Command reference

<!-- generated by docs/gen_cli.py from jlcplace's argument parser: edit the parser's help, then run
     `python docs/gen_cli.py` (tests/test_docs.py fails when this page is out of date) -->

Every command takes `-v` / `--verbose` (log what the EasyEDA client does), before or after the command name.
`BOARD` is a `.kicad_pcb` file or a JSON snapshot written by [`jlcplace snapshot`](#jlcplace-snapshot).
Exit codes are listed in [Exit codes and environment](./environment).
"""


def _parser():
    from jlcplace import cli
    real = cli.default_cache_dir
    cli.default_cache_dir = lambda: CACHE_DEFAULT          # the help text names the default; keep the page portable
    try:
        return cli.build_parser()
    finally:
        cli.default_cache_dir = real


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _flags(action: argparse.Action) -> str:
    if not action.option_strings:
        return f"`{action.metavar or action.dest.upper()}`"
    names = ", ".join(f"`{o}`" for o in action.option_strings)
    if action.nargs == 0:
        return names
    meta = action.metavar or (f"{{{','.join(map(str, action.choices))}}}" if action.choices else action.dest.upper())
    return f"{names} `{meta}`"


def _help(action: argparse.Action, parser: argparse.ArgumentParser) -> str:
    text = action.help or ""
    if "%(" in text:
        text = text % {**vars(action), "prog": parser.prog}
    extra = []
    if action.choices and action.option_strings and "{" not in _flags(action):
        extra.append("one of " + ", ".join(f"`{c}`" for c in action.choices))
    if isinstance(action, argparse._AppendAction) and "repeatable" not in text:
        extra.append("repeatable")
    if extra:
        text = f"{text} ({'; '.join(extra)})" if text else "; ".join(extra)
    return _cell(text)


def _section(name: str, sub: argparse.ArgumentParser, summary: str) -> list[str]:
    summary = _cell(summary)
    lines = [f"## jlcplace {name}", "", (summary[:1].upper() + summary[1:].rstrip(".") + ".") if summary else "", ""]
    if sub.description and sub.description.strip() != summary.strip():
        lines += [sub.description.strip(), ""]
    usage = "\n".join(l[len("usage: "):] if l.startswith(" " * len("usage: ")) else l.removeprefix("usage: ")
                      for l in sub.format_usage().rstrip().splitlines())
    lines += ["```text", usage, "```", ""]
    for group in sub._action_groups:
        rows = [a for a in group._group_actions
                if a.help is not argparse.SUPPRESS and not isinstance(a, argparse._HelpAction)]
        if not rows:
            continue
        title = {"positional arguments": "Arguments", "options": "Options",
                 "optional arguments": "Options"}.get(group.title, group.title[:1].upper() + group.title[1:])
        lines += [f"### {title}" if title != "Arguments" else "**Arguments**", ""]
        lines += ["| | |", "|---|---|"]
        lines += [f"| {_flags(a)} | {_help(a, sub)} |" for a in rows]
        lines.append("")
    if sub.epilog:
        lines += [sub.epilog.strip(), ""]
    return lines


def render() -> str:
    parser = _parser()
    subs = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    summaries = {c.dest: c.help or "" for c in subs._choices_actions}
    lines = [HEADER]
    for name, sub in subs.choices.items():
        lines += _section(name, sub, summaries.get(name, ""))
    text = "\n".join(lines)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text.rstrip() + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the page is out of date")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date: run python docs/gen_cli.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
